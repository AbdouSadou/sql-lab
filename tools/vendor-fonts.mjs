// Copies the interface and code typefaces from their npm packages into vendor/fonts/ and writes
// css/fonts.css. Dev tooling, not deployed; run it after changing the package versions:
//
//   npm ci && node tools/vendor-fonts.mjs
//
// Atkinson Hyperlegible Next (interface) and Atkinson Hyperlegible Mono (SQL, identifiers, data),
// SIL Open Font License 1.1, from @fontsource-variable. Only the latin and latin-ext subsets, upright
// and italic: about 170 KB in all, and a browser downloads a subset only when the page uses a
// character in its unicode-range.

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "vendor", "fonts");
const FAMILIES = [
    { pkg: "atkinson-hyperlegible-next", family: "Atkinson Hyperlegible Next" },
    { pkg: "atkinson-hyperlegible-mono", family: "Atkinson Hyperlegible Mono" },
];
const SUBSETS = ["latin", "latin-ext"];
const STYLES = [
    { css: "wght.css", style: "normal" },
    { css: "wght-italic.css", style: "italic" },
];

mkdirSync(OUT_DIR, { recursive: true });
const faces = [];
for (const { pkg, family } of FAMILIES) {
    const dir = path.join(ROOT, "node_modules", "@fontsource-variable", pkg);
    const version = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8")).version;
    copyFileSync(path.join(dir, "LICENSE"), path.join(OUT_DIR, `${pkg}.LICENSE.txt`));
    for (const { css, style } of STYLES) {
        const text = readFileSync(path.join(dir, css), "utf8");
        for (const subset of SUBSETS) {
            const file = `${pkg}-${subset}-wght-${style}.woff2`;
            // the block of this subset: its comment names it exactly
            const block = text.split("/* ").find((part) => part.startsWith(`${pkg}-${subset}-wght-${style} */`));
            const range = block?.match(/unicode-range:\s*([^;]+);/)?.[1];
            const weight = block?.match(/font-weight:\s*([^;]+);/)?.[1];
            if (!range || !weight) {
                throw new Error(`${pkg} ${style} ${subset}: no @font-face block in ${css}`);
            }
            copyFileSync(path.join(dir, "files", file), path.join(OUT_DIR, file));
            faces.push(
                `/* ${family} ${version}, ${subset}, ${style} */\n` +
                    `@font-face {\n` +
                    `    font-family: "${family}";\n` +
                    `    font-style: ${style};\n` +
                    `    font-weight: ${weight};\n` +
                    `    font-display: swap;\n` +
                    `    src: url("../vendor/fonts/${file}") format("woff2");\n` +
                    `    unicode-range: ${range};\n` +
                    `}\n`
            );
        }
    }
}

writeFileSync(
    path.join(ROOT, "css", "fonts.css"),
    "/* Generated by tools/vendor-fonts.mjs from @fontsource-variable packages; do not edit by hand.\n" +
        "   The files are in vendor/fonts/ with their licence (SIL Open Font License 1.1). The fallbacks\n" +
        "   (system-ui, ui-monospace) are in the --font-ui and --font-mono tokens (css/tokens.css). */\n\n" +
        faces.join("\n")
);
console.log(`${faces.length} faces written to css/fonts.css, files in vendor/fonts/`);
